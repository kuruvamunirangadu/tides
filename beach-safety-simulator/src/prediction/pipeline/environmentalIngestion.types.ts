/**
 * environmentalIngestion.types.ts
 * 
 * TIDES — Phase 7: Predictive Coastal Risk Intelligence
 * 
 * Strict data contracts for environmental observation ingestion,
 * sensor provenance, data freshness, and validity handling.
 * 
 * Non-Negotiable Rules:
 * - Distinguish missing data (null) from measured zero (0.0).
 * - Explicitly mark provenance (MEASURED vs SIMULATED vs SYNTHETIC).
 * - Validate timestamp sanity, physical range boundaries, and unit consistency.
 */

export type EnvironmentalVariable =
  | 'WIND_SPEED'              // km/h
  | 'WIND_DIRECTION'          // degrees (0-360)
  | 'WAVE_HEIGHT'             // meters
  | 'WAVE_PERIOD'             // seconds
  | 'WAVE_DIRECTION'          // degrees (0-360)
  | 'TIDE_LEVEL'              // meters
  | 'TIDE_CHANGE_RATE'        // m/hr
  | 'WATER_CURRENT_SPEED'     // m/s
  | 'WATER_CURRENT_DIRECTION' // degrees (0-360)
  | 'WATER_TEMPERATURE'       // Celsius
  | 'VISIBILITY'              // km
  | 'WEATHER_CONDITION';      // string category

export type ObservationQuality =
  | 'VALID'           // Within physical bounds, timely, verified
  | 'STALE'           // Exceeds freshness max latency
  | 'OUT_OF_BOUNDS'   // Physically impossible or corrupt measurement
  | 'MISSING'         // Sensor reported null/disconnect (distinct from zero)
  | 'DEGRADED';       // High noise, degraded sensor telemetry, or partial failure

export type DataProvenance =
  | 'MEASURED'        // Physical oceanographic sensor / beach weather gateway
  | 'SIMULATED'       // Generated by active digital twin simulation engine
  | 'SYNTHETIC';      // Controlled test harness / historical offline benchmark

export interface EnvironmentalObservation {
  id: string;
  sensorId: string;
  variable: EnvironmentalVariable;
  value: number | string | null;  // null strictly indicates MISSING
  unit: string;
  timestamp: number;              // Source observation epoch ms
  ingestedAt: number;             // Pipeline ingestion epoch ms
  location: {
    zoneId: string;
    coordinates?: { x: number; y: number };
  };
  quality: ObservationQuality;
  isMissing: boolean;
  provenance: DataProvenance;
  freshnessSeconds: number;       // (now - timestamp) / 1000
  metadata?: {
    modelOrMake?: string;
    sampleRateHz?: number;
    errorMargin?: number;
    notes?: string;
  };
}

export interface VariablePhysicalBounds {
  min: number;
  max: number;
  maxDeltaPerSecond: number; // For rate-of-change spike detection
  expectedUnits: string[];
}

export interface SensorMetadata {
  sensorId: string;
  name: string;
  variable: EnvironmentalVariable;
  zoneId: string;
  provenance: DataProvenance;
  unit: string;
  maxStalenessSeconds: number;
  lastObservation?: EnvironmentalObservation;
  health: 'OPERATIONAL' | 'DEGRADED' | 'STALE' | 'OFFLINE';
  lastSeenMs?: number;
}

export interface ObservationIngestionResult {
  accepted: boolean;
  observation?: EnvironmentalObservation;
  rejectionReason?: string;
  isDuplicate?: boolean;
  isOutOfBounds?: boolean;
  isStale?: boolean;
}

export interface EnvironmentalDataQualitySummary {
  totalSensors: number;
  operationalSensors: number;
  staleSensors: number;
  missingDataCount: number;
  provenanceBreakdown: Record<DataProvenance, number>;
  averageFreshnessSeconds: number;
  pipelineHealth: 'HEALTHY' | 'DEGRADED' | 'CRITICAL';
}

