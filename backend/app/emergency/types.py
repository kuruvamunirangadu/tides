"""
backend/app/emergency/types.py
Data structures and contracts for TIDES Milestone 9:
Intelligent Emergency Coordination & Evacuation.
"""

from enum import Enum
from typing import Dict, List, Optional, Any, Tuple
from pydantic import BaseModel, Field
import time


class EvacuationZoneState(str, Enum):
    """Configurable emergency demonstration states for beach zones."""
    NORMAL = "NORMAL"                # Standard operational swimming/beach area
    CAUTION = "CAUTION"              # Moderate hazard / elevated surveillance
    RESTRICTED = "RESTRICTED"        # Water entry prohibited, bathers recalled
    EVACUATION = "EVACUATION"        # Active mandatory area clearance
    UNAVAILABLE = "UNAVAILABLE"      # Physical route blocked or zone unsafe


class EmergencyActionType(str, Enum):
    """Demonstration recommendations generated by the Emergency Decision Support Policy."""
    INCREASE_PATROL = "INCREASE_PATROL"
    PUBLIC_WARNING = "PUBLIC_WARNING"
    RESTRICT_ZONE = "RESTRICT_ZONE"
    PREPARE_RESOURCES = "PREPARE_RESOURCES"
    EVACUATE_ZONE = "EVACUATE_ZONE"
    CLOSE_ROUTE = "CLOSE_ROUTE"


class RecommendationStatus(str, Enum):
    RECOMMENDED = "RECOMMENDED"
    OPERATOR_APPROVED = "OPERATOR_APPROVED"
    OPERATOR_REJECTED = "OPERATOR_REJECTED"


class IncidentStatus(str, Enum):
    REPORTED = "REPORTED"
    DISPATCHED = "DISPATCHED"
    ON_SCENE = "ON_SCENE"
    RESOLVED = "RESOLVED"
    UNRESOLVED_RESOURCE_EXHAUSTION = "UNRESOLVED_RESOURCE_EXHAUSTION"


class Point2D(BaseModel):
    x: float
    y: float


class EvacuationZone(BaseModel):
    """Designated spatial safety and evacuation sector on the beach."""
    zone_id: str
    name: str
    x_min: float
    x_max: float
    y_min: float
    y_max: float
    state: EvacuationZoneState = EvacuationZoneState.NORMAL
    reason: str = "Standard patrolled conditions"
    hazard_refs: List[str] = Field(default_factory=list)
    state_changed_at: float = Field(default_factory=time.time)
    is_operator_confirmed: bool = False
    active_visitor_count: int = 0


class EmergencyIncident(BaseModel):
    """
    Standardized multi-incident tracking item.
    Enforces deterministic priority scoring and avoids conflicting resource assignments.
    """
    incident_id: str
    visitor_id: str
    location: Point2D
    distress_level: float = Field(..., ge=0.0, le=1.0)
    priority_score: float = Field(default=0.0, ge=0.0, description="Calculated priority score")
    status: IncidentStatus = IncidentStatus.REPORTED
    assigned_resource_id: Optional[str] = None
    assigned_resource_name: Optional[str] = None
    created_at: float = Field(default_factory=time.time)
    dispatched_at: Optional[float] = None
    resolved_at: Optional[float] = None
    notes: Optional[str] = None


class EmergencyRecommendation(BaseModel):
    """Explainable decision-support guidance for operations commander."""
    recommendation_id: str
    target_zone_id: Optional[str] = None
    target_incident_id: Optional[str] = None
    action_type: EmergencyActionType
    rule_triggered: str
    supporting_inputs: Dict[str, Any]
    uncertainty_notes: Optional[str] = None
    status: RecommendationStatus = RecommendationStatus.RECOMMENDED
    created_at: float = Field(default_factory=time.time)
    reviewed_at: Optional[float] = None
    reviewed_by: Optional[str] = None


class EvacuationExit(BaseModel):
    """Designated safe exit path off the sand onto promenade or high ground."""
    exit_id: str
    name: str
    location: Point2D
    flow_capacity_visitors_per_sec: float = 1.2  # Max pedestrian clearance throughput
    current_queue_count: int = 0
    is_blocked: bool = False
    blocked_reason: Optional[str] = None


class EvacuationRoute(BaseModel):
    """Walkable sand corridor connecting beach zones to safe exits."""
    route_id: str
    name: str
    origin_zone_id: str
    exit_id: str
    waypoints: List[Point2D]
    is_blocked: bool = False
    bottleneck_location: Optional[Point2D] = None
    occupant_count: int = 0


class EmergencyPerformanceMetrics(BaseModel):
    """Quantified response metrics derived strictly from event records (N/A when absent)."""
    evacuation_completion_pct: Optional[float] = Field(default=None, description="Percentage of affected visitors safely evacuated")
    warning_to_movement_delay_sec: Optional[float] = Field(default=None, description="Average delay from alert broadcast to initial evacuation movement")
    visitors_remaining_in_hazard_zones: int = 0
    route_utilization_pct: Optional[float] = None
    queue_length_avg: Optional[float] = None
    resource_utilization_pct: Optional[float] = None
    unresolved_incidents_count: int = 0
    scenario_duration_sec: Optional[float] = None
